// views-firmware.jsx, Firmware assurance digest, status, device token, build provenance.

const { Card: FwCard, KV: FwKV, Tag: FwTag, Badge: FwBadge, Hr: FwHr, Sev: FwSev,
        Kpi: FwKpi, Tabs: FwTabs, EvBind: FwEv, Callout: FwCallout, Code: FwCode, EmptyState: FwEmpty } = window.UI;
const { HashChip: FwHash, OriginChip: FwOrigin, EvBind2: FwEvBind2,
        DetailRow: FwDetail, StatGrid: FwSGrid, Stat: FwStat,
        ChecksList: FwChecks } = window.UIX;
const FwP = window.PQCP;
const FwS = window.STORE;

function FirmwareView({ session, pack }) {
  const refv = FwS.referenceValues(pack);
  const fw = FwS.firmwareStatus(pack);
  const tok = FwS.deviceEvidenceToken(pack);

  return (
    <>
      <div className="grid-kpi" style={{ marginBottom: 12 }}>
        <FwKpi label="Digest root" status={refv?.expected_firmware_digest_root ? "ok" : "warn"}
               value={refv?.expected_firmware_digest_root ? "hash-bound" : "n/a"}
               sub={refv ? `${refv.firmware_digest_artifact_count} bound artifacts` : "awaiting pqc_reference_values.json"}
               evbind={<FwEvBind2 ev={refv?.evbind} compact />} />
        <FwKpi label="Firmware status" status={fw?.passed === true ? "ok" : fw?.passed === false ? "err" : "warn"}
               value={fw ? (fw.passed ? "verified" : "fail") : "n/a"}
               sub={fw ? `${(fw.checks || []).length} checks` : "awaiting firmware_assurance_status_result.json"}
               evbind={<FwEvBind2 ev={fw?.evbind} compact />} />
        <FwKpi label="Device evidence token" status={tok?.passed === true ? "ok" : tok?.passed === false ? "err" : "warn"}
               value={tok ? (tok.passed ? "matched" : "fail") : "n/a"}
               sub={tok ? `${(tok.checks || []).length} checks` : "awaiting device_evidence_token_result.json"}
               evbind={<FwEvBind2 ev={tok?.evbind} compact />} />
        <FwKpi label="Hardware evidence" status="warn"
               value="optional"
               sub="not required outside hardware_review mode" />
        <FwKpi label="Embeddable header" status="warn"
               value={FwS.evbind(pack, "generated/pqcp_assurance_digest_generated.h").status === "present" ? "present" : "n/a"}
               sub="generated/pqcp_assurance_digest_generated.h"
               evbind={<FwEvBind2 ev={FwS.evbind(pack, "generated/pqcp_assurance_digest_generated.h")} compact />} />
      </div>

      <div className="grid grid-12">
        {/* Digest manifest */}
        <FwCard span={6} kicker="Assurance digest" title="Hash-bound, not signed"
              subtitle="SHA-256 digest manifest over ledger, CBOM, attestation, transcripts, benchmark provenance, release manifest."
              actions={<FwEvBind2 ev={refv?.evbind} compact />}>
          {!refv ? (
            <FwEmpty icon="○" title="Awaiting pqc_reference_values.json" hint="Generated by scripts/generate_pqc_reference_values.py." />
          ) : (
            <>
              <FwDetail k="digest_root" v={refv.expected_firmware_digest_root ? <FwHash sha={refv.expected_firmware_digest_root} full /> : null} />
              <FwDetail k="artifact_count" v={refv.firmware_digest_artifact_count != null ? <span className="mono">{refv.firmware_digest_artifact_count}</span> : null} />
              <FwDetail k="attestation subjects" v={refv.attestation_subject_count != null ? <span className="mono">{refv.attestation_subject_count}</span> : null} />
              <FwDetail k="transcript_count" v={refv.transcript_count != null ? <span className="mono">{refv.transcript_count}</span> : null} />
              <FwHr />
              <div className="kv__k" style={{ marginBottom: 6 }}>Bound artifacts</div>
              <div className="subjgrid">
                {Object.entries(refv.artifact_hashes).map(([name, h]) => (
                  <div key={name} className="subjrow">
                    <span className="subjrow__f">{name}</span>
                    <span className="subjrow__h"><FwHash sha={h.sha256} /></span>
                    <FwTag tone="ok">{h.size_bytes != null ? `${h.size_bytes} B` : "bound"}</FwTag>
                  </div>
                ))}
              </div>
            </>
          )}
        </FwCard>

        {/* Firmware status (assurance_status sample) */}
        <FwCard span={6} kicker="Firmware assurance status" title={fw ? (fw.passed ? "Transcript verified against reference values" : "Verification failed") : "Awaiting firmware_assurance_status_result.json"}
              subtitle="samples/pqcp_assurance_status emits PQCP_ASSURANCE_STATUS and PQCP_ASSURANCE_ARTIFACT lines; the verifier re-hashes each line against reference values."
              actions={<FwEvBind2 ev={fw?.evbind} compact />}>
          {!fw ? (
            <FwEmpty icon="○" title="No firmware status result" hint="Produced by scripts/verify_firmware_assurance_status.py once the QEMU sample run is captured." />
          ) : (
            <>
              <FwSGrid>
                <FwStat k="passed" v={fw.passed ? "true" : "false"} />
                <FwStat k="status" v={typeof fw.status === "string" ? fw.status : fw.status ? "ok" : "n/a"} />
                <FwStat k="artifacts" v={(fw.artifacts || []).length} />
                <FwStat k="checks" v={(fw.checks || []).length} />
              </FwSGrid>
              <FwHr />
              <div className="kv__k" style={{ marginBottom: 6 }}>Verified artifacts</div>
              <div className="subjgrid">
                {(fw.artifacts || []).slice(0, 12).map(a => (
                  <div key={a.name} className="subjrow">
                    <span className="subjrow__f">{a.name}</span>
                    <span className="subjrow__h"><FwHash sha={a.sha256} /></span>
                    <FwTag tone="ok">match</FwTag>
                  </div>
                ))}
              </div>
              {(fw.checks || []).length > 0 && (
                <>
                  <FwHr />
                  <div className="kv__k" style={{ marginBottom: 6 }}>Per-check results</div>
                  <FwChecks items={fw.checks} max={40} />
                </>
              )}
            </>
          )}
        </FwCard>

        {/* Device evidence token */}
        <FwCard span={6} kicker="Device evidence token" title="schema v7 additive marker"
              subtitle="Token emitted by firmware that binds nonce + digest + artifact count + transcript binding back to reference values."
              actions={<FwEvBind2 ev={tok?.evbind} compact />}>
          {!tok ? (
            <FwEmpty icon="○" title="Awaiting device_evidence_token_result.json" />
          ) : (
            <FwChecks items={tok.checks} max={20} />
          )}
        </FwCard>

        {/* Embeddable header preview */}
        <FwCard span={6} kicker="Firmware-embeddable header" title="generated/pqcp_assurance_digest_generated.h"
              subtitle="Generated by scripts/export_firmware_assurance_digest.py; embedded by samples/pqcp_assurance_status."
              actions={<FwEvBind2 ev={FwS.evbind(pack, "generated/pqcp_assurance_digest_generated.h")} compact />}>
          <FwCode label="C">{`/* generated/pqcp_assurance_digest_generated.h */
#define PQCP_ASSURANCE_DIGEST_ROOT      "${refv?.expected_firmware_digest_root || "<awaiting>"}"
#define PQCP_ASSURANCE_ARTIFACT_COUNT   ${refv?.firmware_digest_artifact_count ?? "/* awaiting */"}
#define PQCP_ASSURANCE_SCHEMA_VERSION   ${refv?.schema_version ?? "/* awaiting */"}`}</FwCode>
          <FwCallout tone="info">
            The token bound at boot is <strong>hash-bound, not identity-signed</strong>. A future firmware-side
            attestation that signs over this digest with a hardware key is out of scope for this release.
          </FwCallout>
        </FwCard>

        {/* SLSA build provenance */}
        <FwCard span={12} kicker="SLSA-shaped build provenance" title="unsigned in-toto Statement"
              subtitle="Subjects, resolved dependencies, external parameters, byproduct hashes. Replay-checked by scripts/verify_pqc_build_provenance.py."
              actions={<FwEvBind2 ev={FwS.evbind(pack, "pqc_build_provenance.slsa.json")} />}>
          <FwEmpty icon="○" title="Build-provenance section not yet in this pack"
            hint="When present, this card will render subjects + dependencies + external parameters + replay checks. The pack format already reserves the slot." />
        </FwCard>
      </div>
    </>
  );
}

window.VIEW_FIRMWARE = { FirmwareView };
