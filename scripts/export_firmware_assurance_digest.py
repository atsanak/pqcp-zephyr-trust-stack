"""Export pqc_assurance_digest.json into a firmware-embeddable C header."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

HEX64 = re.compile(r"^[0-9a-f]{64}$")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--digest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument(
        "--version",
        default="unknown",
        help="Release version string to embed in PQCP_ASSURANCE_STATUS.",
    )
    return parser.parse_args()


def load_digest(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"assurance digest not found: {path}")
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise RuntimeError("assurance digest root must be a JSON object")
    if raw.get("schema_version") != 1:
        raise RuntimeError(f"unsupported assurance digest schema_version {raw.get('schema_version')!r}")
    if raw.get("digest_algorithm") != "sha256":
        raise RuntimeError(f"unsupported assurance digest algorithm {raw.get('digest_algorithm')!r}")
    artifacts = raw.get("artifacts")
    if not isinstance(artifacts, list) or not artifacts:
        raise RuntimeError("assurance digest must contain at least one artifact")
    for index, artifact in enumerate(artifacts):
        if not isinstance(artifact, dict):
            raise RuntimeError(f"artifact {index} must be a JSON object")
        sha = artifact.get("sha256")
        if not isinstance(sha, str) or not HEX64.fullmatch(sha):
            raise RuntimeError(f"artifact {index} has invalid sha256 {sha!r}")
        path_value = artifact.get("path")
        if not isinstance(path_value, str) or not path_value:
            raise RuntimeError(f"artifact {index} has invalid path")
    return raw


def canonical_digest_root(digest: dict[str, Any]) -> str:
    canonical = json.dumps(digest, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(canonical).hexdigest()


def c_string(value: str) -> str:
    return json.dumps(value)


def render_header(digest: dict[str, Any], *, source_name: str, version: str) -> str:
    root_hash = canonical_digest_root(digest)
    artifact_count = len(digest["artifacts"])
    generated_at = datetime.now(timezone.utc).isoformat()
    artifact_names = ", ".join(c_string(str(item["path"])) for item in digest["artifacts"])
    artifact_hashes = ", ".join(c_string(str(item["sha256"])) for item in digest["artifacts"])
    return "\n".join(
        [
            "/*",
            " * SPDX-License-Identifier: LicenseRef-Proprietary-Collaborative-Evaluation",
            " *",
            " * Generated by scripts/export_firmware_assurance_digest.py.",
            " * Do not edit by hand.",
            " */",
            "",
            "#ifndef PQCP_ASSURANCE_DIGEST_GENERATED_H_",
            "#define PQCP_ASSURANCE_DIGEST_GENERATED_H_",
            "",
            f'#define PQCP_ASSURANCE_DIGEST_SOURCE "{source_name}"',
            f"#define PQCP_ASSURANCE_DIGEST_VERSION {c_string(version)}",
            '#define PQCP_ASSURANCE_DIGEST_ALGORITHM "sha256"',
            "#define PQCP_ASSURANCE_DIGEST_SCHEMA_VERSION 1",
            f"#define PQCP_ASSURANCE_DIGEST_ARTIFACT_COUNT {artifact_count}",
            f'#define PQCP_ASSURANCE_DIGEST_ROOT_SHA256 "{root_hash}"',
            f'#define PQCP_ASSURANCE_DEVICE_EVIDENCE_NONCE "{root_hash[:32]}"',
            f'#define PQCP_ASSURANCE_DEVICE_EVIDENCE_TRANSCRIPT_SHA256 "{root_hash}"',
            f'#define PQCP_ASSURANCE_DIGEST_GENERATED_AT "{generated_at}"',
            "",
            "static const char * const pqcp_assurance_digest_artifact_names[] = {",
            f"\t{artifact_names}",
            "};",
            "static const char * const pqcp_assurance_digest_artifact_sha256[] = {",
            f"\t{artifact_hashes}",
            "};",
            "",
            "#endif /* PQCP_ASSURANCE_DIGEST_GENERATED_H_ */",
            "",
        ]
    )


def export_header(digest_path: Path, output_path: Path, *, version: str = "unknown") -> dict[str, Any]:
    digest = load_digest(digest_path)
    header = render_header(digest, source_name=digest_path.name, version=version)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(header, encoding="utf-8")
    return {
        "schema_version": 1,
        "digest_path": str(digest_path),
        "output": str(output_path),
        "artifact_count": len(digest["artifacts"]),
        "root_sha256": canonical_digest_root(digest),
    }


def main() -> int:
    args = parse_args()
    try:
        result = export_header(args.digest, args.output, version=args.version)
    except (OSError, RuntimeError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    print("Firmware assurance digest header generated")
    print(f"  output: {result['output']}")
    print(f"  artifacts: {result['artifact_count']}")
    print(f"  root_sha256: {result['root_sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
